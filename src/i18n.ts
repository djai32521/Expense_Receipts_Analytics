import { useSyncExternalStore } from "react";

export type Language = "ko" | "en";
const KEY = "shoebox-language";
let language: Language = "ko";
try { language = localStorage.getItem(KEY) === "en" ? "en" : "ko"; } catch { /* Storage is optional. */ }
const listeners = new Set<() => void>();

export function setLanguage(next: Language) {
  language = next;
  try { localStorage.setItem(KEY, next); } catch { /* Private browsing. */ }
  document.documentElement.lang = next;
  document.title = next === "ko" ? "Shoebox | AI 영수증 분석·지출 관리" : "Shoebox | AI Receipt & Expense Analytics";
  listeners.forEach((notify) => notify());
}

export function useLanguage() {
  return useSyncExternalStore(
    (notify) => { listeners.add(notify); return () => { listeners.delete(notify); }; },
    () => language,
  );
}

